#!/usr/bin/env bash
# Stage 2A-5d-4c — deploys the analyze-case Edge Function to the Supabase STAGING
# project, and nothing else. Run it yourself, from recovery-prototype/ in a GitHub
# Codespace (docs/stage-2a/DEPLOY-STAGE-2A-5D-4C.md). It never runs on its own.
#
# Before anything is sent it checks, and refuses (exit 2) otherwise:
#   * the checkout is the development branch, clean, identical to the pushed
#     branch, and contains Stage 2A-5d-3b (the spending controls in the pipeline);
#   * the function code contains no AI-provider SDK, endpoint or key;
#   * you type the staging project reference back exactly;
#   * the access token you paste (hidden) is shaped like a Supabase access token.
# Then it deploys ONLY analyze-case (never every function, never --prune), with the
# platform's JWT check ON (verify_jwt = true; never --no-verify-jwt), bundled by
# Supabase (--use-api, no Docker), from a throwaway project directory holding a
# copy of supabase/functions and a config.toml generated by the pinned CLI.
# Finally it sets the only two function settings: ANALYSIS_PROVIDER=fake and
# ALLOW_FAKE_PROVIDER=staging-only. Spending, the database and every other
# project are untouched. The token is passed only in the CLI's environment and
# is never printed, stored or put on a command line.
set -euo pipefail

REF=aqwdwswpmbnzmkvyuqil
BRANCH=claude/revenue-recovery-engine-stage-1-8xg8vf
REQUIRED_COMMIT=9ee3767ffbcca3706709c39469a74a19a033de62 # Stage 2A-5d-3b
CLI=supabase@2.117.0
FN=analyze-case

refuse() { echo "REFUSED (nothing deployed): $*" >&2; exit 2; }

[ -f "supabase/functions/$FN/index.ts" ] && [ -d supabase/functions/_shared ] || refuse "run this from recovery-prototype/"
[ "$(git rev-parse --abbrev-ref HEAD)" = "$BRANCH" ] || refuse "the checkout is not on $BRANCH"
[ -z "$(git status --porcelain)" ] || refuse "the checkout has uncommitted or untracked changes"
git merge-base --is-ancestor "$REQUIRED_COMMIT" HEAD 2>/dev/null || refuse "the checkout does not contain Stage 2A-5d-3b"
git fetch -q origin "$BRANCH" || refuse "could not fetch $BRANCH to compare"
[ "$(git rev-parse HEAD)" = "$(git rev-parse "origin/$BRANCH")" ] || refuse "the checkout differs from the pushed branch (run: git pull --ff-only)"
if grep -rqE '@anthropic-ai|api\.anthropic\.com|sk-ant-|ANTHROPIC_API_KEY|openai|x-api-key' supabase/functions; then refuse "the function code contains an AI-provider SDK, endpoint or key"; fi

echo "Function:   $FN"
echo "Commit:     $(git rev-parse --short HEAD) on $BRANCH"
echo "Project:    $REF  (Supabase STAGING — the only project this script deploys to)"
echo "Settings:   ANALYSIS_PROVIDER=fake, ALLOW_FAKE_PROVIDER=staging-only; JWT check ON; spending unchanged (disabled)"
read -r -p "Type the project reference to confirm: " typed
[ "$typed" = "$REF" ] || refuse "the project reference was not confirmed"
read -rs -p "Supabase access token (hidden): " token; echo
[[ "$token" =~ ^sbp_[A-Za-z0-9_]{20,}$ ]] || { token=''; refuse "that is not a Supabase personal access token (sbp_…)"; }

work="$(mktemp -d)"
trap 'token=""; rm -rf "$work"' EXIT
(cd "$work" && npx --yes "$CLI" init </dev/null >/dev/null) || refuse "the Supabase CLI could not prepare a project directory"
mkdir -p "$work/supabase/functions"
cp -R "supabase/functions/$FN" supabase/functions/_shared "$work/supabase/functions/"
printf '\n[functions.%s]\nverify_jwt = true\n' "$FN" >> "$work/supabase/config.toml"

cli() { SUPABASE_ACCESS_TOKEN="$token" npx --yes "$CLI" "$@" --project-ref "$REF" --workdir "$work"; }

echo "== Deploying $FN to $REF"
cli functions deploy "$FN" --use-api || { echo "DEPLOY FAILED: nothing else was changed. Send this output." >&2; exit 1; }
echo "== Setting the function's provider settings (fake, staging only)"
cli secrets set ANALYSIS_PROVIDER=fake ALLOW_FAKE_PROVIDER=staging-only \
  || { echo "SETTINGS FAILED: the function is deployed but refuses every call (503 PROVIDER_NOT_CONFIGURED). Send this output." >&2; exit 1; }
echo "== Deployed functions"
cli functions list
echo "DEPLOYED. Next: bash supabase/scripts/analyze-case-live-check.sh — then revoke the access token."
